// One-off converter: a prepared RGBA bitmap → built-in figure motifs (line art + filled silhouette).
// usage: tsx scripts/make-figure.ts <file.rgba> <width> <height> <id> <Label> <out.ts>
import { readFileSync, writeFileSync } from 'node:fs';
import { traceImageData } from '../src/lib/importArt';
import { bbox, clean, shapeArea, union } from '../src/lib/geom';
import type { Shape } from '../src/lib/types';

const [, , file, W, H, id, label, out] = process.argv;
const data = new Uint8ClampedArray(readFileSync(file));
const traced = traceImageData({ width: +W, height: +H, data } as unknown as ImageData, { threshold: 0.5, invert: false });
const bb = bbox(traced)!;
const w = bb.maxX - bb.minX, h = bb.maxY - bb.minY, cx = (bb.minX + bb.maxX) / 2, cy = (bb.minY + bb.maxY) / 2;
// simplify at a 1000-unit scale, then store in the unit box
const big = (s: Shape[]) => s.map((p) => ({ outer: p.outer.map((q) => ({ x: ((q.x - cx) / w) * 1000 * (w / Math.max(w, h)), y: ((q.y - cy) / h) * 1000 * (h / Math.max(w, h)) })), holes: p.holes.map((r) => r.map((q) => ({ x: ((q.x - cx) / w) * 1000 * (w / Math.max(w, h)), y: ((q.y - cy) / h) * 1000 * (h / Math.max(w, h)) }))) }));
const count = (s: Shape[]) => s.reduce((t, p) => t + p.outer.length + p.holes.reduce((u, r) => u + r.length, 0), 0);
const thin = (s: Shape[], max: number) => { let tol = 0.3, r = clean(s, tol); while (count(r) > max && tol < 12) { tol *= 1.35; r = clean(s, tol); } return r; };
const lines = thin(big(traced).filter((p) => shapeArea(p) > 40), 3200).map((p) => ({ ...p, holes: p.holes.filter((r) => r.length >= 4) }));
const main = big(traced).sort((a, b) => shapeArea(b) + 0 - shapeArea(a))[0];
const solid = thin(union(big(traced).filter((p) => Math.abs(shapeArea(p)) > 400).map((p) => ({ outer: p.outer, holes: [] }))), 520);
void main;
const kx = Math.max(w, h) / w / 1000, ky = Math.max(w, h) / h / 1000;
const pack = (s: Shape[]) => JSON.stringify(s.map((p) => [p.outer, ...p.holes].map((r) => r.flatMap((q) => [+(q.x * kx).toFixed(4), +(q.y * ky).toFixed(4)]))));
writeFileSync(out, `// Generated by scripts/make-figure.ts from user-supplied artwork — do not edit by hand.
// Each shape is [outer, ...holes]; each ring is a flat [x0, y0, x1, y1, …] list in the unit box.
export const ${id.toUpperCase()}_ASPECT = ${(w / h).toFixed(4)};
export const ${id.toUpperCase()}_LINES: number[][][] = ${pack(lines)};
export const ${id.toUpperCase()}_SOLID: number[][][] = ${pack(solid)};
`);
console.log(label, 'aspect', (w / h).toFixed(3), 'line-art points', count(lines), 'shapes', lines.length, '| silhouette points', count(solid), 'shapes', solid.length);
