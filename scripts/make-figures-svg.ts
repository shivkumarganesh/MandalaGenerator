// Converter for supplied single-path SVG artwork → built-in figure motifs (line art + silhouette).
// usage: tsx scripts/make-figures-svg.ts <out.ts> <id=file.svg> [<id=file.svg> …]
import { readFileSync, writeFileSync } from 'node:fs';
import parse from 'parse-svg-path';
import abs from 'abs-svg-path';
import normalize from 'normalize-svg-path';
import bezier from 'adaptive-bezier-curve';
import { bbox, clean, fromRingsEvenOdd, offset, shapeArea, union } from '../src/lib/geom';
import type { Ring, Shape } from '../src/lib/types';

const [, , out, ...items] = process.argv;
const count = (s: Shape[]) => s.reduce((t, p) => t + p.outer.length + p.holes.reduce((u, r) => u + r.length, 0), 0);
const thin = (s: Shape[], max: number) => { let tol = 0.25, r = clean(s, tol); while (count(r) > max && tol < 12) { tol *= 1.3; r = clean(s, tol); } return r; };
const pack = (s: Shape[], kx: number, ky: number) => JSON.stringify(s.map((p) => [p.outer, ...p.holes].map((r) => r.flatMap((q) => [+(q.x * kx).toFixed(4), +(q.y * ky).toFixed(4)]))));

let body = '// Generated by scripts/make-figures-svg.ts from user-supplied artwork — do not edit by hand.\n// Each shape is [outer, ...holes]; each ring is a flat [x0, y0, x1, y1, …] list in the unit box.\nexport const FIGURE_DATA: Record<string, { aspect: number; lines: number[][][]; solid: number[][][] }> = {\n';
for (const item of items) {
  const [id, file] = item.split('=');
  const svg = readFileSync(file, 'utf8');
  const rings: Ring[] = [];
  for (const m of svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)) {
    let cur: Ring = [], pen = [0, 0];
    for (const s of normalize(abs(parse(m[1]))) as (string | number)[][]) {
      if (s[0] === 'M') { if (cur.length > 2) rings.push(cur); pen = [s[1] as number, s[2] as number]; cur = [{ x: pen[0], y: pen[1] }]; }
      else if (s[0] === 'C') { const pts = bezier(pen, [s[1], s[2]], [s[3], s[4]], [s[5], s[6]], 3) as number[][]; for (let i = 1; i < pts.length; i++) cur.push({ x: pts[i][0], y: pts[i][1] }); pen = [s[5] as number, s[6] as number]; }
    }
    if (cur.length > 2) rings.push(cur);
  }
  const raw = fromRingsEvenOdd(rings);
  const bb = bbox(raw)!;
  const w = bb.maxX - bb.minX, h = bb.maxY - bb.minY, cx = (bb.minX + bb.maxX) / 2, cy = (bb.minY + bb.maxY) / 2, k = 1000 / Math.max(w, h);
  const big = raw.map((p) => ({ outer: p.outer.map((q) => ({ x: (q.x - cx) * k, y: (q.y - cy) * k })), holes: p.holes.map((r) => r.map((q) => ({ x: (q.x - cx) * k, y: (q.y - cy) * k }))) }));
  // pen lines are thickened a little (2 units in 1000) so they survive cutting at wall-art sizes
  const lines = thin(offset(big, 2).filter((p) => shapeArea(p) > 30), 2100).map((p) => ({ ...p, holes: p.holes.filter((r) => r.length >= 4) }));
  const solid = thin(union(big.filter((p) => shapeArea(p) > 300).map((p) => ({ outer: p.outer, holes: [] }))), 420);
  const kx = Math.max(w, h) / w / 1000, ky = Math.max(w, h) / h / 1000;
  body += `  ${JSON.stringify(id)}: { aspect: ${(w / h).toFixed(4)}, lines: ${pack(lines, kx, ky)}, solid: ${pack(solid, kx, ky)} },\n`;
  console.log(id, 'aspect', (w / h).toFixed(3), '| line-art', count(lines), 'pts', lines.length, 'shapes | silhouette', count(solid), 'pts', solid.length, 'shapes');
}
writeFileSync(out, body + '};\n');
